"use client";

import { useEffect, useRef, useState } from "react";
import {
  AlertOctagon,
  Baby,
  BedDouble,
  Droplets,
  Eye,
  Flame,
  Footprints,
  Loader2,
  Thermometer,
  Volume2,
  Waves,
  Wind,
  X,
  Zap,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { useLocale } from "@/components/providers/locale-provider";
import { postJson } from "@/lib/http-client";
import { GO_TO_HOSPITAL, SIGN_CAN_BE_DANGEROUS } from "@/services/pregnancy/danger-signs";
import type { DangerResponse, PregnancyView } from "./types";

const ICONS = {
  droplets: Droplets,
  eye: Eye,
  zap: Zap,
  thermometer: Thermometer,
  flame: Flame,
  wind: Wind,
  baby: Baby,
  waves: Waves,
  footprints: Footprints,
  bed: BedDouble,
} as const;

type Sign = PregnancyView["dangerSigns"][number];

/**
 * Shown the instant a sign is tapped, before the server answers: the instruction is
 * fixed text, so no network delay or error can hold it back. The family alert and the
 * QR code arrive underneath when the request returns.
 */
function HospitalScreen({
  sign,
  pregnancyId,
  onClose,
}: {
  sign: Sign;
  pregnancyId: string;
  onClose: () => void;
}) {
  const { t } = useLocale();
  const closeRef = useRef<HTMLButtonElement>(null);
  const [result, setResult] = useState<DangerResponse | null>(null);
  const [failed, setFailed] = useState(false);

  useEffect(() => {
    closeRef.current?.focus();
    let cancelled = false;
    postJson<DangerResponse>(`/api/pregnancy/${pregnancyId}/danger`, { sign: sign.id })
      .then((response) => !cancelled && setResult(response))
      .catch(() => !cancelled && setFailed(true));
    return () => {
      cancelled = true;
    };
  }, [pregnancyId, sign.id]);

  return (
    <div
      role="alertdialog"
      aria-modal="true"
      aria-labelledby="hospital-title"
      className="fixed inset-0 z-[60] overflow-y-auto bg-red-700 text-white"
    >
      <div className="mx-auto flex max-w-xl flex-col gap-6 px-6 py-10">
        <h2 id="hospital-title" className="flex items-center gap-3">
          <AlertOctagon className="size-12 shrink-0" aria-hidden="true" />
          <span>
            <span className="font-urdu block text-4xl leading-loose" lang="ur" dir="rtl">
              {GO_TO_HOSPITAL.ur}
            </span>
            <span className="block text-2xl font-bold">{GO_TO_HOSPITAL.roman}</span>
            <span className="block text-lg">{GO_TO_HOSPITAL.en}</span>
          </span>
        </h2>

        <div className="space-y-1 rounded-lg bg-white/10 p-4">
          <p className="font-urdu text-2xl leading-loose" lang="ur" dir="rtl">{sign.text.ur}</p>
          <p className="font-semibold">{sign.text.roman}</p>
          <p className="text-sm">{sign.text.en}</p>
          <p className="font-urdu pt-2 text-xl leading-loose" lang="ur" dir="rtl">{SIGN_CAN_BE_DANGEROUS.ur}</p>
          <p className="text-sm">{SIGN_CAN_BE_DANGEROUS.en}</p>
        </div>

        <div aria-live="assertive" className="space-y-4">
          {!result && !failed && (
            <p className="flex items-center gap-2">
              <Loader2 className="size-5 animate-spin" aria-hidden="true" />
              {t("mother.hospital.sending")}
            </p>
          )}
          {failed && <p className="rounded bg-white/15 p-3 font-semibold">{t("mother.hospital.failed")}</p>}
          {result && (
            <>
              <p className="text-lg font-semibold">
                {result.caregiversWithAlerts > 0
                  ? `${result.caregiversNotified} ${t("mother.hospital.notified")}`
                  : t("mother.hospital.noFamily")}
              </p>
              <div className="space-y-2 rounded-lg bg-white p-4 text-gray-900">
                <div
                  className="mx-auto size-56 [&_svg]:size-full"
                  role="img"
                  aria-label={t("mother.summary.button")}
                  // Generated by our own server from the summary link; contains no user input.
                  dangerouslySetInnerHTML={{ __html: result.emergency.qrSvg }}
                />
                <p className="text-center text-sm">{t("mother.hospital.qr")}</p>
                <p className="break-all text-center text-xs" dir="ltr">{result.emergency.url}</p>
              </div>
            </>
          )}
        </div>

        <Button
          ref={closeRef}
          size="lg"
          className="h-14 w-full bg-white text-base text-red-800 hover:bg-white/90"
          onClick={onClose}
        >
          {t("mother.danger.close")}
        </Button>
      </div>
    </div>
  );
}

export function DangerSigns({
  view,
  onClose,
}: {
  view: PregnancyView;
  onClose: () => void;
}) {
  const { t } = useLocale();
  const [active, setActive] = useState<Sign | null>(null);
  const titleRef = useRef<HTMLHeadingElement>(null);

  useEffect(() => {
    titleRef.current?.focus();
  }, []);

  const play = (sign: Sign) => {
    new Audio(sign.audio).play().catch(() => {});
  };

  return (
    <div role="dialog" aria-modal="true" aria-labelledby="danger-title" className="fixed inset-0 z-50 overflow-y-auto bg-background">
      <div className="mx-auto max-w-4xl space-y-5 px-4 py-6">
        <div className="flex items-start justify-between gap-4">
          <h2 id="danger-title" ref={titleRef} tabIndex={-1} className="text-2xl font-semibold text-red-700 dark:text-red-400">
            {t("mother.danger.title")}
          </h2>
          <Button variant="ghost" size="icon-lg" onClick={onClose} aria-label={t("mother.danger.close")}>
            <X className="size-5" aria-hidden="true" />
          </Button>
        </div>

        <ul className="grid gap-4 sm:grid-cols-2">
          {view.dangerSigns.map((sign) => {
            const Icon = ICONS[sign.icon];
            return (
              <li key={sign.id} className="flex flex-col gap-3 rounded-xl border-2 border-red-600/40 p-4">
                <div className="flex items-start gap-3">
                  <span className="flex size-14 shrink-0 items-center justify-center rounded-full bg-red-600/10 text-red-700 dark:text-red-400">
                    <Icon className="size-7" aria-hidden="true" />
                  </span>
                  <div className="space-y-1">
                    <p className="font-urdu text-xl leading-loose" lang="ur" dir="rtl">{sign.text.ur}</p>
                    <p className="font-medium">{sign.text.roman}</p>
                    <p className="text-sm text-muted-foreground">{sign.text.en}</p>
                  </div>
                </div>
                <div className="mt-auto flex flex-wrap gap-2">
                  {sign.audioRecorded && (
                    <Button variant="outline" size="lg" className="h-12" onClick={() => play(sign)}>
                      <Volume2 className="size-4" aria-hidden="true" />
                      {t("mother.danger.listen")}
                    </Button>
                  )}
                  <Button
                    size="lg"
                    className="h-12 flex-1 bg-red-700 text-base text-white hover:bg-red-800"
                    onClick={() => setActive(sign)}
                  >
                    {t("mother.danger.happening")}
                  </Button>
                </div>
              </li>
            );
          })}
        </ul>
      </div>

      {active && <HospitalScreen sign={active} pregnancyId={view.pregnancy.id} onClose={() => setActive(null)} />}
    </div>
  );
}
